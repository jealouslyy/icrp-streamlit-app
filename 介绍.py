import streamlit as st

st.title("呼吸道颗粒物沉积计算软件")

st.markdown(
    """
    ### 基于 ICRP 模型的颗粒物呼吸道沉积与剂量分析平台
    本软件面向颗粒物呼吸暴露研究与结果展示，支持不同人群、呼吸方式和活动状态下的呼吸道沉积计算。
    可实现单粒径、粒径点列表、粒径段分布及多分散气溶胶等情形下的沉积分数、沉积剂量与结果导出。
    """
)

st.markdown("---")

c1, c2 = st.columns(2)
with c1:
    st.info(
        """
        **沉积分数计算**
        
        支持单粒径、粒径点列表和粒径段输入，
        计算前鼻区域、后鼻-咽喉区域、支气管区域、细支气管区域与肺泡-间质区域各呼吸道部位沉积分数。
        """
    )
    st.info(
        """
        **多分散气溶胶计算**
        
        基于质量中位粒径和几何标准差，
        计算多分散气溶胶粒径分布及区域沉积结果。
        """
    )

with c2:
    st.info(
        """
        **沉积剂量计算**
        
        结合颗粒物浓度、暴露时长与活动状态，
        计算呼吸道各区域沉积剂量。
        """
    )
    st.info(
        """
        **结果展示与导出**
        
        支持结果表格、柱状图展示，
        并可导出CSV文件用于后续分析。
        """
    )

st.markdown("---")
st.subheader("使用流程")
st.markdown(
    """
    1. 在左侧导航栏选择功能页面  
    2. 设置人群、呼吸方式和颗粒物参数  
    3. 输入粒径、浓度或分布参数  
    4. 点击计算并查看结果图表  
    5. 按需导出CSV结果文件  
    """
)

st.caption("建议在情景对比分析中保持除目标变量外的其他参数一致，以便比较不同粒径或暴露条件对沉积结果的影响。")
